const { chromium, devices } = require('playwright');
const fs = require('fs');
const path = require('path');
const { OUT, wrap } = require('./lib.cjs');
const TMP = wrap('creator');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file://' + TMP);
  await p.waitForTimeout(300);
  const ok = (n, c) => console.log((c ? 'PASS ' : 'FAIL ') + n);
  await p.tap('#tab-draw');
  const stroke = async (pts) => {
    const box = await p.locator('#pad').boundingBox();
    const at = ([x, y]) => [box.x + box.width * x, box.y + box.height * y];
    const [x0, y0] = at(pts[0]);
    await p.mouse.move(x0, y0);
    await p.mouse.down();
    for (const q of pts.slice(1)) {
      const [x, y] = at(q);
      await p.mouse.move(x, y, { steps: 6 });
    }
    await p.mouse.up();
    await p.waitForTimeout(80);
  };
  await p.locator('#pad').scrollIntoViewIfNeeded();
  await stroke([[0.3, 0.55], [0.4, 0.6], [0.3, 0.65]]);
  ok('face layer saved', (await p.evaluate(() => S.draw.face.length)) === 1);
  await p.tap('#dl-h1');
  await p.locator('#pad').scrollIntoViewIfNeeded();
  await stroke([[0.36, 0.5], [0.42, 0.46], [0.46, 0.5]]);
  await stroke([[0.55, 0.5], [0.6, 0.46], [0.65, 0.5]]);
  await stroke([[0.43, 0.62], [0.5, 0.68], [0.57, 0.62]]);
  ok('hand expression saved (3 strokes)', (await p.evaluate(() => S.draw.h1.length)) === 3);
  ok('hand expression chip shows and is selected', (await p.evaluate(() => view.expr)) === 'h1' && !!(await p.$('#expr .chip:has-text("手绘表情 1")')));
  ok('original features hidden for h1', await p.evaluate(() => drawPerson(S, 'calm', 'adult') !== drawPerson(S, 'h1', 'adult')));
  await p.locator('#pad').screenshot({ path: path.join(OUT, 'pad-h1.png') });
  await p.tap('#d-undo');
  ok('undo removes last stroke', (await p.evaluate(() => S.draw.h1.length)) === 2);
  await stroke([[0.43, 0.62], [0.5, 0.7], [0.57, 0.62]]);
  await p.tap('#dl-face');
  await p.tap('#d-erase');
  await p.locator('#pad').scrollIntoViewIfNeeded();
  await stroke([[0.3, 0.55], [0.4, 0.6]]);
  ok('eraser removes the face stroke', (await p.evaluate(() => S.draw.face.length)) === 0);
  await p.tap('#d-erase');
  await p.tap('#dl-cloth');
  await p.locator('#pad').scrollIntoViewIfNeeded();
  await stroke([[0.2, 0.2], [0.8, 0.8]]);
  await stroke([[0.8, 0.2], [0.2, 0.8]]);
  ok('cloth pattern saved and switched on', await p.evaluate(() => S.draw.cloth.length === 2 && S.pattern === 'custom'));
  await p.tap('#dl-emblem');
  await p.locator('#pad').scrollIntoViewIfNeeded();
  await stroke([[0.5, 0.15], [0.85, 0.5], [0.5, 0.85], [0.15, 0.5], [0.5, 0.15]]);
  ok('emblem saved', (await p.evaluate(() => S.draw.emblem.length)) === 1);
  ok('renders clean', await p.evaluate(() => !/NaN|undefined/.test(['calm', 'h1', 'happy'].map((e) => ['child', 'adult', 'elder'].map((a) => drawPerson(S, e, a)).join('')).join(''))));
  ok('share code carries drawings', await p.evaluate(() => { const o = decode(encode(S)); return o.draw.h1.length === 3 && o.draw.cloth.length === 2; }));
  ok('no horizontal overflow', !(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth)));
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.waitForTimeout(100);
  await p.screenshot({ path: path.join(OUT, 'draw-mobile.png') });
  console.log('errors', errs);
  await b.close();
})();
