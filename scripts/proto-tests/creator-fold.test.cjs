const { chromium, devices } = require('playwright');
const fs = require('fs');
const path = require('path');
const { OUT, wrap } = require('./lib.cjs');
const TMP = wrap('creator');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file://' + TMP);
  await p.evaluate(() => localStorage.clear());
  await p.reload();
  await p.waitForTimeout(300);
  const ok = (n, c) => console.log((c ? 'PASS ' : 'FAIL ') + n);
  const visible = (sel) => p.evaluate((s) => { const e = document.querySelector(s); return !!e && e.offsetParent !== null; }, sel);
  await p.tap('#tab-features');
  ok('fine sliders hidden by default', !(await visible('#r-eyeY')) && !(await visible('#r-mouthSize')));
  ok('part choices shown', await visible('#o-eyes-' + (await p.evaluate(() => OPT.eyes[1][0]))));
  ok('4 folds on features (glasses off)', (await p.$$('.fold')).length === 4);
  await p.tap('#fold-features-1');
  ok('eye fold opens', await visible('#r-eyeY'));
  ok('no badge before change', !(await visible('#tw-features-1')));
  await p.fill('#r-eyeY', '0.9');
  await p.dispatchEvent('#r-eyeY', 'input');
  ok('badge shows after change', (await visible('#tw-features-1')) && (await p.textContent('#tw-features-1')) === '改过 1 项');
  await p.tap('#fold-features-1');
  ok('fold closes, badge stays', !(await visible('#r-eyeY')) && (await visible('#tw-features-1')));
  await p.tap('#fold-features-1');
  await p.tap('#fr-features-1');
  ok('reset puts eyeY back', await p.evaluate(() => S.eyeY === DEFAULT.eyeY));
  ok('fold still open after reset', await visible('#r-eyeY'));
  await p.tap('#fold-all');
  ok('expand all opens every fold', await p.evaluate(() => [...document.querySelectorAll('.fine-body')].every((e) => !e.hidden)));
  ok('button says 全部收起', (await p.textContent('#fold-all')) === '全部收起');
  await p.reload();
  await p.waitForTimeout(200);
  ok('open state remembered after reload', await visible('#r-mouthSize'));
  await p.tap('#fold-all');
  ok('collapse all', await p.evaluate(() => [...document.querySelectorAll('.fine-body')].every((e) => e.hidden)));
  // glasses on → glasses fold appears
  await p.tap('#o-glasses-round');
  ok('glasses fold appears', (await p.$$('.fold')).length === 5);
  // every tab renders and has no overflow
  for (const t of ['body', 'face', 'features', 'hair', 'outfit', 'acc', 'expr', 'persona', 'draw', 'share']) {
    await p.tap('#tab-' + t);
    await p.waitForTimeout(50);
    const o = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    if (o) ok('overflow on ' + t, false);
  }
  ok('no horizontal overflow on any tab', true);
  await p.tap('#tab-outfit');
  await p.tap('#fold-outfit-0');
  await p.tap('#pk-trimColor');
  ok('color picker works inside fold', await visible('#h-trimColor'));
  await p.tap('#tab-features');
  await p.tap('#fold-features-2');
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.screenshot({ path: path.join(OUT, 'fold-mobile.png'), fullPage: true });
  const d = await b.newContext({ viewport: { width: 1280, height: 860 } });
  const pd = await d.newPage();
  pd.on('pageerror', (e) => errs.push('desktop: ' + e.message));
  await pd.goto('file://' + TMP);
  await pd.evaluate(() => { localStorage.clear(); });
  await pd.reload();
  await pd.click('#tab-features');
  await pd.waitForTimeout(200);
  await pd.screenshot({ path: path.join(OUT, 'fold-desktop.png') });
  console.log('errors', errs);
  await b.close();
})();
